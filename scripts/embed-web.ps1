#Requires -Version 7.2
[CmdletBinding()]
param([switch]$SkipBuild)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $false
$root = Split-Path $PSScriptRoot -Parent
if (-not $SkipBuild) {
    Push-Location $root
    try {
        & npm run build:web
        if ($LASTEXITCODE -ne 0) { throw 'Frontend production build failed.' }
    } finally { Pop-Location }
}
$web = Join-Path $root 'apps/web/dist'
if (-not (Test-Path -LiteralPath (Join-Path $web 'index.html'))) { throw 'No frontend index.html. Build the production frontend first.' }
function Swift-String([string]$Value) {
    return '"' + $Value.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t') + '"'
}
$types = @{ '.html'='text/html; charset=utf-8'; '.js'='text/javascript; charset=utf-8'; '.css'='text/css; charset=utf-8'; '.json'='application/json'; '.svg'='image/svg+xml'; '.png'='image/png'; '.jpg'='image/jpeg'; '.jpeg'='image/jpeg'; '.gif'='image/gif'; '.webp'='image/webp'; '.ico'='image/x-icon'; '.woff'='font/woff'; '.woff2'='font/woff2'; '.ttf'='font/ttf'; '.mp4'='video/mp4'; '.webm'='video/webm'; '.wasm'='application/wasm' }
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by scripts/embed-web.ps1; do not edit or commit.')
$lines.Add('#if WEBDROP_EMBED_WEB')
$lines.Add('import Foundation')
$lines.Add('enum EmbeddedWebBundle {')
$lines.Add('    static let files: [String: WebAsset] = [')
$total = 0L; $count = 0
foreach ($file in (Get-ChildItem -LiteralPath $web -File -Recurse | Sort-Object FullName)) {
    $relative = [IO.Path]::GetRelativePath($web, $file.FullName).Replace('\', '/')
    if (@($relative.Split('/') | Where-Object { $_.StartsWith('.') }).Count -gt 0) { continue }
    $contentType = if ($types.ContainsKey($file.Extension.ToLowerInvariant())) { $types[$file.Extension.ToLowerInvariant()] } else { 'application/octet-stream' }
    # Only Vite content-hashed assets are immutable; index/public files revalidate.
    $immutable = if ($relative -match '^assets/.+-[A-Za-z0-9_-]{8,}\.[^/]+$') { 'true' } else { 'false' }
    $bytes = [IO.File]::ReadAllBytes($file.FullName)
    $base64 = [Convert]::ToBase64String($bytes)
    $lines.Add('        ' + (Swift-String "/$relative") + ': WebAsset(bytes: Data(base64Encoded: "' + $base64 + '")!, contentType: ' + (Swift-String $contentType) + ', immutable: ' + $immutable + '),')
    $total += $bytes.Length; $count++
}
$lines.Add('    ]')
$lines.Add('}')
$lines.Add('#endif')
$directory = Join-Path $root 'apps/api/Sources/WebdropAPI/Generated'
$null = New-Item -ItemType Directory -Force -Path $directory
$path = Join-Path $directory 'EmbeddedWebAssets.generated.swift'
$content = ($lines -join "`n") + "`n"
# Keep incremental builds stable when frontend output is unchanged.
if (-not (Test-Path $path) -or [IO.File]::ReadAllText($path) -cne $content) { [IO.File]::WriteAllText($path, $content, [Text.UTF8Encoding]::new($false)) }
Write-Host "Embedded $count frontend files ($total bytes)."
